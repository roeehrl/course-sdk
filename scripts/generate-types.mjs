// Generates TypeScript declarations from src/course.schema.json. Every `$defs` entry becomes
// `S<Name>`; `SchemaContracts` and `SchemaRecords` map each public kind to its definition and
// `SchemaCourseManifest` is the root. tests/generated-types.test.ts proves the hand-written
// public types and these generated ones accept exactly the same values (mutual assignability),
// so a schema change that is not reflected in the types fails `npm run typecheck`.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { CONTRACT_DEFINITIONS, RECORD_DEFINITIONS } from './contract-map.mjs';

const root = new URL('../', import.meta.url);
const schema = JSON.parse(await readFile(new URL('src/course.schema.json', root), 'utf8'));
const defs = schema.$defs;

const typeName = name => `S${name[0].toUpperCase()}${name.slice(1)}`;
const key = name => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));
const literal = value => JSON.stringify(value);
const SUPPORTED = new Set(['type', '$ref', 'properties', 'required', 'additionalProperties', 'unevaluatedProperties', 'enum', 'const', 'oneOf', 'items',
  // Validation-only keywords with no TypeScript counterpart.
  'minItems', 'maxItems', 'uniqueItems', 'minimum', 'maximum', 'exclusiveMinimum', 'minLength', 'maxLength', 'pattern', 'format', 'minProperties', 'maxProperties', 'default',
  'description', 'title', '$schema', '$id', '$defs']);

function expression(node, path, inheritedRequired = new Set()) {
  if (node === true || (node && typeof node === 'object' && Object.keys(node).length === 0)) return 'Json';
  for (const keyword of Object.keys(node)) if (!SUPPORTED.has(keyword)) throw new Error(`${path}: unsupported keyword ${keyword}; extend the type generator.`);
  if (node.$ref) {
    if (!node.$ref.startsWith('#/$defs/') || !(node.$ref.slice(8) in defs)) throw new Error(`${path}: unsupported $ref ${node.$ref}.`);
    return typeName(node.$ref.slice(8));
  }
  if ('const' in node) return literal(node.const);
  if (node.enum) return node.enum.map(literal).join(' | ');
  const base = objectOrScalar(node, path, inheritedRequired);
  if (node.oneOf) {
    // Variants share the base object's required names (JSON Schema applies both).
    const shared = new Set([...inheritedRequired, ...(base === undefined ? [] : node.required ?? [])]);
    const variants = node.oneOf.map((variant, i) => `(${expression(variant, `${path}/oneOf/${i}`, shared)})`).join(' | ');
    return base === undefined ? variants : `${base} & (${variants})`;
  }
  if (base === undefined) throw new Error(`${path}: cannot derive a type.`);
  return base;
}

function objectOrScalar(node, path, inheritedRequired) {
  switch (node.type) {
    case undefined: return node.properties || node.required ? objectType(node, path, inheritedRequired) : undefined;
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `(${node.items ? expression(node.items, `${path}/items`) : 'Json'})[]`;
    case 'object': return objectType(node, path, inheritedRequired);
    default: throw new Error(`${path}: unsupported type ${JSON.stringify(node.type)}.`);
  }
}

function objectType(node, path, inheritedRequired = new Set()) {
  const properties = node.properties ?? {};
  const required = new Set([...(node.required ?? []), ...[...inheritedRequired].filter(name => name in properties)]);
  if (!Object.keys(properties).length && !required.size) return '{ [key: string]: Json }';
  const members = Object.entries(properties).map(([name, value]) =>
    `${key(name)}${required.has(name) ? '' : '?'}: ${expression(value, `${path}/properties/${name}`)};`);
  // Required names declared without a property schema are constrained by the variants.
  for (const name of required) if (!(name in properties)) members.push(`${key(name)}: unknown;`);
  return `{ ${members.join(' ')} }`;
}

const lines = [
  '// Generated by scripts/generate-types.mjs from src/course.schema.json. Do not edit.',
  "import type { Json } from '../types.js';",
  '',
];
for (const name of Object.keys(defs).sort()) lines.push(`export type ${typeName(name)} = ${expression(defs[name], `#/$defs/${name}`)};`);
const { $defs: _defs, $schema: _schema, $id: _id, ...rootNode } = schema;
lines.push('', `export type SchemaCourseManifest = ${expression(rootNode, '#')};`);
const map = (title, entries) => [`export interface ${title} {`, ...Object.entries(entries).map(([kind, def]) => `  ${key(kind)}: ${typeName(def)};`), '}'];
lines.push('', ...map('SchemaContracts', CONTRACT_DEFINITIONS), '', ...map('SchemaRecords', RECORD_DEFINITIONS), '');
await mkdir(new URL('src/generated/', root), { recursive: true });
await writeFile(new URL('src/generated/schema-types.d.ts', root), lines.join('\n'));
